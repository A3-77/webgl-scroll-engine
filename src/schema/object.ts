/**
 * ★ Schema —— 场景对象契约
 * ---------------------------------------------------------------------------
 * 改造前叫 `LayerConfig`，定义在 `config/scenes.ts` 里。
 * 改名 `SceneObjectConfig` 的理由：
 *   "layer"（图层）暗示"一张平面贴图"，但这个契约要同时表达
 *   plane / model / 以及以后可能的 sprite、video、group —— 它是**场景里的一个对象**，
 *   不只是 Photoshop 意义上的图层。
 * ---------------------------------------------------------------------------
 *
 * 兼容性：`layer` 这个词在 shader 与调试面板里仍然有意义（z 排序），
 * 所以对象数组仍叫 `objects`，但内部字段（z / overscan / fit / tracks）语义不变。
 */

import type { ObjectAnimation, Track } from './animation';

export interface SceneObjectConfig {
  id: string;
  /** 素材 key（由内容包注册），不是路径 */
  asset: string;

  /**
   * ★ 这个对象在场景里**扮演什么角色**。
   *
   * ---------------------------------------------------------------------------
   * 【为什么要这个字段 —— 修掉一个隐式的命名约定】
   *
   *   改造前，判断"这是不是背景"靠的是 **`obj.id === 'bg'`** ——
   *   一个字符串魔法值同时被自动构图（生产端）和验收脚本（消费端）依赖。
   *   两个问题：
   *     ▸ 命名约定传递语义是脆的：换个 id 就失效，而且看不出这是契约
   *     ▸ 手写内容包不知道有这个约定，写出来的背景不叫 'bg'，
   *       于是验收脚本会把"背景在动"当成"对象独立运动"的证据
   *
   *   现在改成显式的角色声明。和 `isHero: boolean` → `transition.mode` 是同一个
   *   改造思路：**用语义代替含糊的约定**。
   *
   * ---------------------------------------------------------------------------
   * ---------------------------------------------------------------------------
   * 【它表达「是什么」，不是「必须怎样」】
   *
   *   `background` 说的是"这一层在视觉上属于背景"，**不代表它必须静止** ——
   *   远景星点、云、雾有轻微漂移是完全合理的（shopify 包第 2 章就拿一个
   *   GLB 星点模型当背景层，它带 ±0.03 的 x 漂移）。
   *   验收脚本一度断言"背景必须静止"，后来发现是断言写得太武断，已改。
   *
   * ---------------------------------------------------------------------------
   * 【手写内容包也要声明】
   *
   *   自动构图（`asset-pipeline/compose.ts`）会自动填这个字段。
   *   手写 `scenes` 的包**必须自己写** —— role 是契约的一部分，不是可选装饰：
   *   验收脚本靠它区分"背景"和"主体"，缺了就只能报 SKIP，
   *   而 SKIP 意味着"这项没被验证"，不是"这项没问题"。
   *
   * ---------------------------------------------------------------------------
   * 目前只被验收脚本消费。以后可以让 SceneBuilder 按 role 推导默认值
   * （background 默认 opaque + parallax 0），但那是行为变更，单独做。
   */
  role?: 'background' | 'subject' | 'overlay';

  /**
   * 对象类型。
   *   'plane'（默认）—— 一张贴图铺在平面上，MeshBasicMaterial 无光照
   *   'model'        —— 一个 GLB 模型，按包围盒自动缩放居中
   *
   * 两种可以混在同一个场景里（原站就是这么干的：背景是平面，
   * 前景是带骨骼的 GLB 模型）。
   */
  type?: 'plane' | 'model';

  /**
   * 仅 `type: 'model'` —— 把模型缩放到「包围盒高度 = 该值 × 视口高」。
   *
   * 为什么要这个而不是直接用 GLB 自带的 scale：
   *   37 个模型出自不同美术之手，单位尺度完全不统一（有的 0.5，有的 40）。
   *   按包围盒归一化，才能让任何模型一进来就是合适的构图，
   *   换模型时只调这一个数。
   */
  modelHeight?: number;

  /**
   * 仅 `type: 'model'` —— 是否播放模型自带的动画。
   * 默认 false。开启后动画由**滚动进度**驱动（scrub），不是按墙上时钟播放 ——
   * 原站的动画就是挂在 Theatre.js 时间轴上被 sequence.position 拖着走的。
   */
  scrubAnimations?: boolean;

  /**
   * ★ 对象在相机空间的 z 深度（负值 = 越远）。
   *
   * 这是整个 2.5D 视差的**唯一来源**，值得说清楚：
   *   真实站点实测（three devtools 钩子抓的运行时场景图）：
   *     asset-1  Group  position(-0.233, 0.141, -7.09)  scale(2,2,3)
   *     asset-2  Group  position(0, 0, -25.46)          scale 18.901
   *   两者 z 差 18 个单位。配一台 PerspectiveCamera 时，相机往前推 1 个单位，
   *   z=-7 的层在屏幕上放大的倍率远大于 z=-25 的层 ——
   *   视差不需要写任何代码，它是透视投影的几何后果，是硬件免费给的。
   *
   * 所以：**想要视差就拉开 z 的差距**，不要去找什么"视差开关"。
   */
  z: number;

  /** 平面相对"刚好铺满视口"的放大倍数，>1 留出位移余量 */
  overscan: number;

  /**
   * 平面尺寸如何适配视口。**不写这个字段，竖版人像图会被横向拉成三角形。**
   *   'cover'   —— 铺满视口（可能裁切）。抽象背景用这个，默认值。
   *   'contain' —— 按纹理自身宽高比完整放入视口（不裁切、不拉伸）。
   *                有明确形状的中景/前景用这个。
   */
  fit?: 'cover' | 'contain';

  /** 基准偏移，单位 = 该深度处视口高度/宽度的比例 */
  offset: [number, number];

  /** 着色色调，用于在不换图的前提下改冷暖（#ffffff = 原色） */
  tint?: string;

  /** 混合模式：normal 用于实拍层，additive 用于光晕/粒子层 */
  blending?: 'normal' | 'additive';

  /**
   * 该对象是否不透明。
   *
   * ★ 这个字段是为了修一个真实的渲染顺序 bug 才加的。
   *   three 渲染时会先把所有**不透明**物体画完，再画**透明**物体 ——
   *   这个分类发生在排序**之前**，renderOrder 管不了跨列表的先后。
   *
   *   所以「背景平面 transparent:true + 前景模型 opaque」的组合会翻车：
   *   模型先画（不透明列表），背景后画（透明列表），且背景关掉了深度测试，
   *   结果**背景直接把模型盖住**，模型白渲染一场（三角面数还在涨，就是看不见）。
   *
   *   把满幅背景标成 opaque，两者就落进同一个列表，renderOrder 才真正生效。
   *   这也更贴合真实站点 —— 它的背景就是一块不透明的 quad。
   *
   * 默认 false（透明）。带 alpha 的中景/前景剪影要的就是透明，不要改。
   */
  opaque?: boolean;

  /**
   * ★ 视差强度倍率（1 = 完全由 z 深度自然产生）。
   *
   * 为什么需要它：z 深度产生的视差是"物理正确"的，但物理正确 ≠ 好看。
   * 有时想让某只猫动得比几何允许的更夸张一点，又不想为了它改整个 z 布局。
   * 这个倍率只作用于**轨道位移**（不作用于投影本身），所以不会破坏构图。
   *
   * 语义：position 轨道的位移量 × parallax。
   *   0   = 钉死不动（背景常用）
   *   1   = 默认，几何自然视差
   *   1.5 = 夸张的前景冲刺感
   */
  parallax?: number;

  /** 该对象的动画。手写轨道 或 引用预设 */
  animation?: ObjectAnimation;

  /**
   * @deprecated 手写轨道。等价于 `animation: { tracks }`。
   * 保留是为了让改造前的场景配置能原样跑通（PHASE 1 不做行为变更）。
   */
  tracks?: Track[];
}
