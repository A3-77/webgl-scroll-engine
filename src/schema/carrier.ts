/**
 * ★ Schema —— 3D 过渡载体契约
 * ===========================================================================
 * 让过渡不再是"两张平面图像在混合"，而是**一个 3D 物体飞过画面，
 * 溶解边界跟着它走**。
 *
 * ---------------------------------------------------------------------------
 * 【为什么需要这个 —— 对照参考站点】
 *
 *   shader.se（SKY）的 about 场景过渡是这样的：
 *
 *     ▸ 一架 3D 飞机沿 Catmull-Rom 曲线飞过画面
 *     ▸ 飞机身上"挂"着一个小平面，那个小平面上跑过渡 shader
 *     ▸ shader 的溶解边缘用**多频正弦叠加**做成有机的、油墨扩散式的形状
 *     ▸ 于是画面不是在"叠化"，而是在"被飞过的东西擦写"
 *
 *   我们的原实现是纯 2D 的：铺一张阈值图，比较 progress - threshold。
 *   边界再活，它也是**没有主体的** —— 没有一个"东西"在做这件事。
 *   这就是"看起来只是图片转场"的根源。
 *
 * ---------------------------------------------------------------------------
 * 【两件事，分开控制】
 *
 *   ① **载体本身** —— 一个真的 3D 物体飞过画面（`kind` / `preset` / `scale`）
 *   ② **溶解跟随** —— 阈值场的中心从"固定圆心"换成"载体的屏幕位置"（`follow`）
 *
 *   follow = 0 → 完全不跟随，退化成原来的圆形溶解（载体只是个装饰）
 *   follow = 1 → 溶解完全以载体为中心，画面像被它擦开
 *
 *   分开控制是有意的：只想要"有个东西飞过"的内容包可以给 follow=0.2，
 *   想要"画面被擦写"的给 0.9 —— 这是两种完全不同的叙事语气。
 *
 * ---------------------------------------------------------------------------
 * 【★ 为什么默认给 preset 而不是让内容包手写路径】
 *
 *   素材驱动的原则是"丢图进去就出网站"。
 *   要求用户手写一串 Catmull-Rom 控制点（还得理解相机 z / fov / 视锥）
 *   等于把门槛抬回"你得懂 three.js"。
 *
 *   所以默认走 **preset**：引擎按当前相机参数（z / fov / aspect）
 *   算出屏幕边界，自动生成一条合理的飞行路径。
 *   要精确控制时再手写 `path` 覆盖 —— 那是进阶选项，不是必须项。
 * ---------------------------------------------------------------------------
 */

/**
 * 预设路径。引擎按相机参数自动生成，不需要手写坐标。
 *
 *   'fly-across'  —— 从画面左下远处飞到右上近处（SKY 的飞机就是这个走向）
 *   'fly-through' —— 从正前方远处冲向镜头，最后穿过画面（最有冲击力）
 *   'orbit'       —— 绕画面中心转一圈（适合强调"环绕感"）
 *   'rise'        —— 从画面下方升到上方（适合"揭幕"）
 */
export type CarrierPreset = 'fly-across' | 'fly-through' | 'orbit' | 'rise';

/** 程序化几何的形状。没有 GLB 素材时用这些 */
export type CarrierShape = 'plane' | 'box' | 'sphere' | 'cone' | 'torus';

export interface CarrierConfig {
  /** 是否启用。默认 false —— 保持原有纯 2D 过渡行为 */
  enabled?: boolean;

  /** 预设路径。给了 `path` 时本项被忽略 */
  preset?: CarrierPreset;

  /**
   * 显式路径（世界坐标控制点，至少 2 个，建议 3~5 个）。
   * 给这项就完全覆盖 preset —— 需要精确编排时用。
   */
  path?: [number, number, number][];

  /**
   * 载体是什么。
   *   'glb'   —— 用内容包注册的模型资产（填 `model`）
   *   'shape' —— 程序化几何（填 `shape`），零素材依赖
   */
  kind?: 'glb' | 'shape';

  /** kind='glb' 时的资产 key。与 `model` 二选一 */
  model?: string;

  /** kind='shape' 时的几何类型。默认 'plane'（一片"纸"，最像 SKY） */
  shape?: CarrierShape;

  /** 整体缩放。默认 1 */
  scale?: number;

  /**
   * 朝向模式。
   *   'tangent' —— 沿路径切线方向（飞机头朝着前进方向，默认）
   *   'fixed'   —— 不旋转
   *   'spin'    —— 匀速自转（配合 `spin`）
   */
  orient?: 'tangent' | 'fixed' | 'spin';

  /** 每秒自转角速度（弧度，xyz 三轴）。orient='spin' 时生效 */
  spin?: [number, number, number];

  /**
   * ★ 溶解跟随强度 0..1。
   *   0 = 阈值场完全不理载体（载体只是装饰）
   *   1 = 阈值场完全以载体的屏幕位置为中心（画面被它擦开）
   */
  follow?: number;

  /**
   * ★ 有机边缘强度。
   *   多频正弦叠加在溶解边界上 —— 让边界不是圆，而是像油墨扩散的形状。
   *   0 = 干净的圆形，1 = 明显的有机构型。SKY 用的是 0.02 量级的系数乘以这个。
   */
  organic?: number;

  /** 只在过渡进行中显示（uProgress 严格在 0..1 之间）。默认 true */
  onlyDuringTransition?: boolean;

  /** 载体颜色（shape 用）。默认 '#e8e2d6'（纸白） */
  color?: string;

  /**
   * 自发光强度 0..1。
   *   给一点自发光，载体会被 bloom 抓到 —— 飞过时拖出光晕，
   *   这是"有主角"的关键。默认 0.35。
   */
  emissive?: number;
}
